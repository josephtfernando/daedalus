#!/usr/bin/env bash
#
# Daedalus setup wizard — scripts/setup.sh
#
# The owner-driven provisioning surface (SPEC §8.5, ARCHITECTURE §7.7): the one
# place secrets and access are granted. Thirteen stages, in spec order —
# preflight · layout · secrets · owner identity · models · local runner ·
# discord · resources · trust posture · runtime · hardening · verification ·
# handoff. Idempotent and re-runnable: re-run it to repair or to grant more.
#
# Verification (stage 12) is the gate. The wizard never reports success with a
# red item: a failing selftest or a failed hardening assertion exits non-zero.
#
# Provenance: everything above the "STAGES" marker is `template.sh` from the
# /wizard skill, vendored verbatim (no hand-edits). The stages below only point
# ENV_FILE at $DAEDALUS_HOME/.env — the library reads that variable at call
# time — and, in non-interactive mode, shadow pause/confirm/open_url/ask.
#
# Deviations from the stage list, all deliberate:
#   · The secret-store DIR is created 0700, not 0600. A directory needs the
#     execute bit to be traversable, so 0600 would make the store unreadable by
#     Daedalus itself; the product's own SecretStore also uses 0700 for
#     resources/ and resources/creds/. Files inside it are 0600, and
#     $DAEDALUS_HOME (0700) and .env (0600) are asserted as specified.
#   · Stage 10 installs exactly the two named units. The runtime pumps its tick
#     in-process, so daedalus-tick.timer wakes daedalus.service (Persistent, no
#     separate tick service) rather than inventing a CLI verb beyond the pinned
#     `selftest` / `run` / `ask` / `version`.
#   · The master key is written where the runtime reads it —
#     $DAEDALUS_HOME/resources/master.key, Fernet-shaped — so the product adopts
#     it instead of minting a second one.
#   · Stage 11 reports the SPEC extras (quarantine, dashboard loopback +
#     Tailscale Serve) as advisory, never as passes, because nothing exists to
#     assert yet in P0.
#
# Personal data is out of bounds: this script reads no file under $HOME other
# than the state dir it owns, and never prints a secret value.
#
# A wizard walks a human through a manual procedure, step by step.
# Generated by the /wizard skill.
#
# Everything above the "STAGES" marker is the wizard library: do not hand-edit
# it. Author the per-step stages below the marker.

