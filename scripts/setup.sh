# ── non-interactive shims ─────────────────────────────────────────────────
# These shadow library helpers *below* the marker (the library above is never
# edited). Interactive mode uses the originals.
_ni_ask() {
  local key="$1" current
  current=$(_existing "$key" || true)
  [[ -z "$current" ]] && current="${!key:-}"
  printf -v "$key" '%s' "$current"
  if [[ -n "$current" ]]; then
    printf '  %s✓%s %s %s(from .env or environment)%s\n' "$GREEN" "$RESET" "$key" "$DIM" "$RESET"
  else
    warn "no value for $key in non-interactive mode"
  fi
}
