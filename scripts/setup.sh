# choose_tier KEY "Prompt" default — one of auto | ask | block.
choose_tier() {
  local key="$1" prompt="$2" default="$3" input
  while :; do
    printf '  %s%s%s %s[%s]%s ' "$BOLD" "$prompt" "$RESET" "$DIM" "$default" "$RESET"
    read -r input || true
    input="${input:-$default}"
    case "$input" in
      auto|ask|block) printf -v "$key" '%s' "$input"; return 0 ;;
      *) warn "expected one of: auto, ask, block" ;;
    esac
  done
}
