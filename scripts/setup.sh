# toml_get SECTION KEY — read from config.toml; empty when absent/unparsable.
toml_get() {
  python3 -c 'import sys
try:
    import tomllib
    d = tomllib.load(open(sys.argv[1], "rb"))
except Exception:
    sys.exit(0)
v = d.get(sys.argv[2], {}).get(sys.argv[3], "")
print(v)' "$CONFIG_FILE" "$1" "$2" 2>/dev/null || true
}

# toml_set SECTION KEY RAW — idempotently upsert `KEY = RAW` under [SECTION].
toml_set() {
  local section="$1" key="$2" value="$3" tmp
  [[ -f "$CONFIG_FILE" ]] || return 1
  tmp="$(mktemp)"
  awk -v section="$section" -v key="$key" -v value="$value" '
    /^[[:space:]]*\[/ {
      if (insec && !done) { print key " = " value; done = 1 }
      insec = ($0 ~ "^[[:space:]]*\\[" section "\\][[:space:]]*$")
      if (insec) seen = 1
      print; next
    }
    {
      if (insec && $0 ~ "^[[:space:]]*" key "[[:space:]]*=") {
        if (!done) {
          comment = ""
          if (match($0, /[[:space:]]+#/)) comment = substr($0, RSTART)
          print key " = " value comment
          done = 1
        }
        next
      }
      print
    }
    END {
      if (!done) {
        if (!seen) { print ""; print "[" section "]" }
        print key " = " value
      }
    }
  ' "$CONFIG_FILE" > "$tmp" && mv "$tmp" "$CONFIG_FILE"
}

# _write_default_config — the canonical default, emitted by the product itself
# so the two can never drift. There is deliberately no literal fallback here:
# a copied model chain went stale twice in one evening (dead model IDs, then a
# corrected-but-different order), and a wizard that writes a config the runtime
# has moved past is worse than a wizard that stops and says so.
_write_default_config() {
  if python3 - "$ROOT_DIR/src" "$CONFIG_FILE" <<'PY' >/dev/null 2>&1
import sys
sys.path.insert(0, sys.argv[1])
from daedalus.config import default_config_toml
with open(sys.argv[2], "w", encoding="utf-8") as fh:
    fh.write(default_config_toml())
PY
  then
    return 0
  fi
  bad "could not emit the default config from src/daedalus/config.py"
  note "the wizard writes config.toml from the product so the two cannot drift;"
  note "a literal copy here would go stale (it did) — fix the repo, then re-run."
  return 1
}

# _adopt_secret NAME FILE — encrypt FILE into the credential store, then delete
# the plaintext. The runtime reads credentials only from the store (Fernet, with
# the per-install master key); it never reads a loose file, so a plaintext copy
# is pure liability — the owner's gcal client JSON was sitting world-readable.
_adopt_secret() {
  local name="$1" file="$2"
  if [[ ! -f "$file" ]]; then
    warn "no such file: $file — nothing adopted"
    return 1
  fi
  if python3 - "$ROOT_DIR/src" "$DAEDALUS_HOME" "$name" "$file" <<'PY' >/dev/null 2>&1
import sys
sys.path.insert(0, sys.argv[1])
from pathlib import Path

from daedalus.resources.secrets import SecretStore

home, name, src = Path(sys.argv[2]), sys.argv[3], Path(sys.argv[4])
SecretStore(home).put(name, src.read_text(encoding="utf-8"))
PY
  then
    rm -f -- "$file"
    ok "adopted $name into the credential store (encrypted at rest); deleted the plaintext copy"
    return 0
  fi
  bad "could not adopt $name into the credential store"
  return 1
}

# _record_resource NAME CLASS ACCESS CRED_REF SCOPES — a commented placeholder
# in resources/registry.toml, written once. Never a claim that access exists.
_record_resource() {
  local name="$1" class="$2" access="$3" cred="$4" scopes="$5" sc="" s=""
  local -a scope_arr=()
  touch "$REGISTRY_FILE"
  if grep -q "^# resource: ${name}\$" "$REGISTRY_FILE" 2>/dev/null; then
    note "$name is already noted in registry.toml"
    return 0
  fi
  IFS=',' read -ra scope_arr <<< "$scopes"
  for s in "${scope_arr[@]}"; do
    s="${s// /}"
    [[ -n "$sc" ]] && sc+=", "
    sc+="\"${s}\""
  done
  {
    printf '# resource: %s\n' "$name"
    printf '# [[resource]]\n'
    printf '# name     = "%s"\n' "$name"
    printf '# class    = "%s"\n' "$class"
    printf '# access   = "%s"\n' "$access"
    printf '# scopes   = [%s]\n' "$sc"
    printf '# cred_ref = "%s"           # encrypted at rest\n' "$cred"
    printf '# added_at = "%s"\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ)"
    printf '#\n'
  } >> "$REGISTRY_FILE"
  ok "noted $name in registry.toml (commented until the credential exists)"
}

# _provision_local_cli NAME SCOPES NOTE — write an *active* [[resource]] entry for
# a local CLI. A local CLI has no credential, so there is nothing to comment out:
# the entry is the grant. Written by the product itself (like the default config)
# so the file the wizard writes is the file the runtime reads, and a re-run is
# idempotent. SCOPES is comma-separated.
_provision_local_cli() {
  local name="$1" scopes="$2" note="$3"
  # The product's own interpreter, not the system `python3`: the registry reads
  # and writes TOML and belongs to the project's environment. `uv run` is the one
  # way to get there that does not depend on the owner having activated a venv.
  if "${UV_BIN:-uv}" run --project "$ROOT_DIR" python - "$ROOT_DIR/src" "$DAEDALUS_HOME" "$name" "$scopes" "$note" <<'PY' >/dev/null 2>&1
import sys
sys.path.insert(0, sys.argv[1])
from pathlib import Path

from daedalus.resources.registry import ResourceRegistry, provision_local_cli

home, name, scopes, note = (
    Path(sys.argv[2]),
    sys.argv[3],
    [s.strip() for s in sys.argv[4].split(",") if s.strip()],
    sys.argv[5],
)
registry = ResourceRegistry(home / "resources" / "registry.toml")
provision_local_cli(registry, name, scopes=scopes, note=note)
PY
  then
    ok "provisioned $name as a local_cli resource in registry.toml"
    return 0
  fi
  bad "could not provision $name in registry.toml"
  SETUP_FAIL+=("$name not provisioned")
  return 1
}

