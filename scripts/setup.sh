# 11 — Hardening
# ══════════════════════════════════════════════════════════════════════════
stage "Hardening — assertions"
say "Each item is checked, repaired where repair is safe, then reported."

# perms are repairable
check_mode() { # path expected label
  local path="$1" want="$2" label="$3" got
  got="$(mode_of "$path")"
  if [[ "$got" == "$want" ]]; then
    ok "$label is $want"
    return 0
  fi
  chmod "$want" "$path" 2>/dev/null || true
  got="$(mode_of "$path")"
  if [[ "$got" == "$want" ]]; then
    ok "$label repaired to $want"
    return 0
  fi
  bad "$label is $got, expected $want"
  HARDEN_FAIL+=("$label not $want")
  return 1
}
check_mode "$DAEDALUS_HOME" 700 "\$DAEDALUS_HOME ($DAEDALUS_HOME)"
check_mode "$ENV_FILE"      600 "\$DAEDALUS_HOME/.env"
check_mode "$CREDS_DIR"     700 "secret store"

# no plaintext secrets in config.toml (key NAMES are printed, never values)
leak_keys="$(grep -Eio '^[[:space:]]*(token|api_key|secret|password)[a-z_]*' "$CONFIG_FILE" 2>/dev/null \
  | grep -vi 'api_key_env' | sort -u | head -n 5 || true)"
fingerprints="$(grep -Eio '(nvapi-[A-Za-z0-9_-]+|sk-[A-Za-z0-9_-]{8,}|mfa\.[A-Za-z0-9_-]+)' "$CONFIG_FILE" 2>/dev/null | head -n 5 || true)"
if [[ -z "$leak_keys" && -z "$fingerprints" ]]; then
  ok "no plaintext secret values in config.toml"
else
  bad "config.toml may hold a plaintext secret"
  [[ -n "$leak_keys" ]] && note "  suspicious key name(s): $(printf '%s' "$leak_keys" | tr '\n' ' ')"
  [[ -n "$fingerprints" ]] && note "  a value matches a known credential shape"
  note "  values are never printed; move them to $ENV_FILE or the secret store."
  HARDEN_FAIL+=("plaintext secret in config.toml")
fi

# DM allowlist on
allow="$(_existing DISCORD_ALLOWED_USERS || true)"
if [[ "$allow" =~ ^[0-9]{15,25}(,[0-9]{15,25})*$ ]]; then
  IFS=',' read -ra allow_ids <<< "$allow"
  ok "DM allowlist is on (${#allow_ids[@]} user id(s))"
else
  bad "DM allowlist is empty or malformed in $ENV_FILE"
  HARDEN_FAIL+=("DM allowlist empty")
fi

# egress gating on
case "$(toml_get approvals egress_tier)" in
  ask|block) ok "egress is gated (egress_tier = $(toml_get approvals egress_tier))" ;;
  auto)      bad "egress_tier = auto — anything could leave the laptop unattended"
             HARDEN_FAIL+=("egress tier is auto") ;;
  *)         bad "egress_tier is unset in config.toml"
             HARDEN_FAIL+=("egress tier unset") ;;
esac

# posture that does not exist yet in P0 — reported as such, never as a pass
if [[ -f "$ROOT_DIR/src/daedalus/security/quarantine.py" ]]; then
  ok "quarantined-reader module present"
else
  note "quarantine: module not present yet (P0) — advisory"
fi
note "dashboard loopback + Tailscale Serve (never Funnel): a P4 posture, nothing to assert"

if (( ${#HARDEN_FAIL[@]} )); then
  printf '\n'
  bad "hardening reported ${#HARDEN_FAIL[@]} problem(s):"
  for f in "${HARDEN_FAIL[@]}"; do note "  - $f"; done
  RUN_OK=0
fi
pause "Continue to verification?"

