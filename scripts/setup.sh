  confirm()    { return 0; }
  open_url()   { printf '  %s↗ open%s %s %s(not opened non-interactively)%s\n' \
                   "$GREEN" "$RESET" "$1" "$DIM" "$RESET"; }
  ask()        { _ni_ask "$@"; }
  ask_secret() { _ni_ask "$@"; }
